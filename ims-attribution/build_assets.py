"""Generate original GTM import templates, self-contained pixels and plugin ZIP.
The templates use Google's documented import format; live GTM Preview remains required.
"""
import json
import re
from pathlib import Path
import zipfile
ROOT=Path(__file__).resolve().parent

def value(x):
    if isinstance(x,list):return {'type':2,'listItem':[value(i) for i in x]}
    return {'type':1,'string':str(x)}

def permission(name,params=None):
    return {'instance':{'key':{'publicId':name,'versionId':'1'},'param':[{'key':k,'value':value(v)} for k,v in (params or {}).items()]},'isRequired':True}

def template(name,kind,fields,source,permissions):
    info={'type':kind,'id':'cvt_temp_public_id','version':1,'securityGroups':[],
          'displayName':name,'description':'IMS-owned measurement component. Review permissions and test before publishing.','containerContexts':['SERVER']}
    params=[{'type':'TEXT','name':key,'displayName':label,'simpleValueType':True,
             'valueValidators':[{'type':'NON_EMPTY'}]} for key,label in fields]
    terms="By creating or modifying this file you agree to Google's Community Template Gallery Developer Terms of Service: https://developers.google.com/tag-manager/gallery-tos"
    return '\n\n'.join(['___TERMS_OF_SERVICE___',terms,'___INFO___',json.dumps(info,indent=2),
        '___TEMPLATE_PARAMETERS___',json.dumps(params,indent=2),'___SANDBOXED_JS_FOR_SERVER___',source,
        '___SERVER_PERMISSIONS___',json.dumps(permissions,indent=2),'___TESTS___','scenarios: []','___NOTES___','Generated by IMS build_assets.py.'])+'\n'

def build():
    out=ROOT/'dist';out.mkdir(exist_ok=True)
    client=template('IMS HTTP Event Client','CLIENT',[
        ('collectPath','Browser collection path, e.g. /ims/events/client1'),
        ('verifiedPath','Verified purchase path, e.g. /ims/verified'),
        ('allowedOrigins','Exact allowed storefront origins, comma-separated'),('gatewayKey','Private server gateway key')],
        (ROOT/'integrations/sgtm-http-client.js').read_text(),[
          permission('read_request',{'requestAccess':'any','headerAccess':'any','queryParameterAccess':'none'}),
          permission('access_response',{'writeResponseAccess':'any','writeHeaderAccess':'any'}),
          permission('return_response'),permission('run_container')])
    (out/'ims-http-client.tpl').write_text(client)
    tag=template('IMS Ledger Forwarder','TAG',[('endpoint','Exact private IMS bridge endpoint'),('bridgeKey','Private per-client bridge key')],
        (ROOT/'integrations/sgtm-forward-tag.js').read_text(),[
          permission('read_event_data',{'eventDataAccess':'any'}),
          permission('send_http',{'allowedUrls':'specific','urls':['https://*/bridge/*']})])
    (out/'ims-ledger-forwarder.tpl').write_text(tag)
    sdk=(ROOT/'web/pixel.js').read_text()
    installer=(ROOT/'integrations/shopify-custom-pixel.js').read_text()
    # Bundle SDK in Shopify's lax sandbox: no dynamic script load or parent-page gtag needed.
    start=installer.index('let ready;');end=installer.index('async function tracker()')
    replacement="const imsEmbedded=(function(){\n"+sdk+"\nreturn window.IMSAttribution;\n})();\nlet ready;\nfunction sdk(){if(!ready)ready=Promise.resolve(imsEmbedded.create({baseUrl:IMS_BASE,tenant:IMS_TENANT,storage:browser.localStorage,collectUrl:IMS_COLLECT_URL}));return ready;}\n"
    installer=installer[:start]+replacement+installer[end:]
    installer=installer.replace("const IMS_TENANT='replace-client-id';","const IMS_TENANT='replace-client-id';\nconst IMS_COLLECT_URL='https://tags.example.com/ims/events/replace-client-id';")
    (out/'shopify-custom-pixel.js').write_text(installer)
    wp=ROOT/'integrations/wordpress/ims-measurement'
    if wp.exists():
        (wp/'pixel.js').write_text(sdk)
        with zipfile.ZipFile(out/'ims-measurement-woocommerce.zip','w',zipfile.ZIP_DEFLATED) as z:
            for p in wp.rglob('*'):
                if p.is_file():z.write(p,'ims-measurement/'+str(p.relative_to(wp)))
    print(json.dumps({'assets':[p.name for p in out.iterdir()]}))
if __name__=='__main__':build()
